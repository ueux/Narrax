"""Layer 3 — AI interpretations.

Narratives are extracted by an LLM, so they are the least verifiable data in the system. The
schema therefore makes three things structural rather than conventional:

1. **Provenance is mandatory.** A narrative always names the model and prompt version that
   produced it, and the run it belongs to.
2. **Interpretations are append-only.** A narrative belongs to exactly one run; a later run
   produces new rows rather than rewriting these, so an earlier claim stays reproducible.
3. **Evidence lives beside the claim.** `narrative_evidence` is a separate table, and a
   narrative with no evidence rows is not publishable (enforced in `services/`, since a CHECK
   cannot reference another table — see docs/database.md).

`narrative_members` and `narrative_evidence` are deliberately distinct:

* **members** — the discussions attributed to the narrative (its support base);
* **evidence** — the curated citations used to justify it, with a rationale.

`narratives.claim_hash` is a database-generated fingerprint used to stop the same claim being
inserted twice for one run.
"""

from typing import TYPE_CHECKING
from uuid import UUID

from sqlalchemy import (
    CheckConstraint,
    Computed,
    Float,
    ForeignKey,
    ForeignKeyConstraint,
    Index,
    Text,
    UniqueConstraint,
)
from sqlalchemy.dialects.postgresql import UUID as PGUUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database.base import Base
from app.database.models.enums import InferredBy, RelationType, sql_in
from app.database.models.mixins import CreatedAtMixin, TimestampMixin, UUIDPrimaryKeyMixin

if TYPE_CHECKING:
    from app.database.models.temporal import NarrativeSnapshot


class Narrative(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    """An AI-extracted claim attributed to an opinion group, from one run."""

    __tablename__ = "narratives"

    analysis_run_id: Mapped[UUID] = mapped_column(
        ForeignKey("analysis_runs.id", ondelete="CASCADE"), nullable=False
    )
    # Nullable so a narrative can outlive a re-clustering; when set, the composite FK forces
    # the cluster to belong to the same run.
    cluster_id: Mapped[UUID | None] = mapped_column(PGUUID(as_uuid=True), nullable=True)

    claim: Mapped[str] = mapped_column(Text, nullable=False)
    description: Mapped[str] = mapped_column(Text, nullable=False)
    confidence: Mapped[float | None] = mapped_column(Float)

    # Fingerprint of the claim, generated by PostgreSQL. Enables a cheap uniqueness guarantee
    # without indexing a potentially very long text column.
    claim_hash: Mapped[str] = mapped_column(
        Text, Computed("encode(sha256(claim::bytea), 'hex')", persisted=True), nullable=False
    )

    model_name: Mapped[str] = mapped_column(Text, nullable=False)
    model_version: Mapped[str | None] = mapped_column(Text)
    prompt_version: Mapped[str] = mapped_column(Text, nullable=False)

    members: Mapped[list["NarrativeMember"]] = relationship(
        back_populates="narrative", cascade="all, delete-orphan"
    )
    evidence: Mapped[list["NarrativeEvidence"]] = relationship(
        back_populates="narrative", cascade="all, delete-orphan"
    )
    snapshots: Mapped[list["NarrativeSnapshot"]] = relationship(
        back_populates="narrative", cascade="all, delete-orphan"
    )

    __table_args__ = (
        UniqueConstraint("analysis_run_id", "claim_hash", name="uq_narratives_run_claim"),
        # Enables child tables to prove they belong to the same run as this narrative.
        UniqueConstraint("id", "analysis_run_id", name="uq_narratives_id_run"),
        ForeignKeyConstraint(
            ["cluster_id", "analysis_run_id"],
            ["clusters.id", "clusters.analysis_run_id"],
            ondelete="CASCADE",
            name="fk_narratives_cluster_run",
        ),
        CheckConstraint("length(btrim(claim)) > 0", name="claim_not_blank"),
        CheckConstraint("length(btrim(description)) > 0", name="description_not_blank"),
        CheckConstraint("length(btrim(prompt_version)) > 0", name="prompt_version_not_blank"),
        CheckConstraint(
            "confidence IS NULL OR (confidence >= 0 AND confidence <= 1)", name="confidence_range"
        ),
    )

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return f"Narrative(id={self.id!r}, claim={self.claim[:40]!r})"


class NarrativeMember(UUIDPrimaryKeyMixin, CreatedAtMixin, Base):
    """A discussion attributed to a narrative."""

    __tablename__ = "narrative_members"

    narrative_id: Mapped[UUID] = mapped_column(
        ForeignKey("narratives.id", ondelete="CASCADE"), nullable=False
    )
    discussion_id: Mapped[UUID] = mapped_column(
        ForeignKey("discussions.id", ondelete="CASCADE"), nullable=False
    )
    relevance: Mapped[float | None] = mapped_column(Float)

    narrative: Mapped["Narrative"] = relationship(back_populates="members")

    __table_args__ = (
        # Which narratives a discussion supports; also the discussion-delete cascade.
        Index("ix_narrative_members_discussion_id", "discussion_id"),
        UniqueConstraint("narrative_id", "discussion_id", name="uq_narrative_members_pair"),
        CheckConstraint(
            "relevance IS NULL OR (relevance >= 0 AND relevance <= 1)", name="relevance_range"
        ),
    )

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return (
            f"NarrativeMember(narrative={self.narrative_id!r}, discussion={self.discussion_id!r})"
        )


class NarrativeEvidence(UUIDPrimaryKeyMixin, CreatedAtMixin, Base):
    """A citation supporting a narrative, with the reason it was chosen."""

    __tablename__ = "narrative_evidence"

    narrative_id: Mapped[UUID] = mapped_column(
        ForeignKey("narratives.id", ondelete="CASCADE"), nullable=False
    )
    discussion_id: Mapped[UUID] = mapped_column(
        ForeignKey("discussions.id", ondelete="CASCADE"), nullable=False
    )
    relevance: Mapped[float | None] = mapped_column(Float)
    rationale: Mapped[str | None] = mapped_column(Text)

    narrative: Mapped["Narrative"] = relationship(back_populates="evidence")

    __table_args__ = (
        # Where else a discussion is cited; also the discussion-delete cascade.
        Index("ix_narrative_evidence_discussion_id", "discussion_id"),
        UniqueConstraint("narrative_id", "discussion_id", name="uq_narrative_evidence_pair"),
        CheckConstraint(
            "relevance IS NULL OR (relevance >= 0 AND relevance <= 1)", name="relevance_range"
        ),
    )

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return (
            f"NarrativeEvidence(narrative={self.narrative_id!r}, discussion={self.discussion_id!r})"
        )


class NarrativeRelation(UUIDPrimaryKeyMixin, CreatedAtMixin, Base):
    """A typed edge between two narratives."""

    __tablename__ = "narrative_relations"

    from_narrative_id: Mapped[UUID] = mapped_column(
        ForeignKey("narratives.id", ondelete="CASCADE"), nullable=False
    )
    to_narrative_id: Mapped[UUID] = mapped_column(
        ForeignKey("narratives.id", ondelete="CASCADE"), nullable=False
    )

    relation_type: Mapped[str] = mapped_column(Text, nullable=False)
    confidence: Mapped[float | None] = mapped_column(Float)
    # Kept explicit so an ML similarity edge is never confused with an LLM judgement.
    inferred_by: Mapped[str] = mapped_column(Text, nullable=False)
    method_version: Mapped[str | None] = mapped_column(Text)

    __table_args__ = (
        # Short explicit name: the convention-generated name would exceed PostgreSQL's
        # 63-character identifier limit.
        # Inbound edges ("what contradicts this narrative?") and the narrative-delete cascade.
        # The primary lookup direction (from_narrative_id) is already indexed by the unique
        # constraint below, whose leading column it is.
        Index("ix_narrative_relations_to_narrative_id", "to_narrative_id"),
        UniqueConstraint(
            "from_narrative_id",
            "to_narrative_id",
            "relation_type",
            "inferred_by",
            name="uq_narrative_relations_edge",
        ),
        CheckConstraint("from_narrative_id <> to_narrative_id", name="no_self_relation"),
        CheckConstraint(sql_in("relation_type", RelationType), name="relation_type_valid"),
        CheckConstraint(sql_in("inferred_by", InferredBy), name="inferred_by_valid"),
        CheckConstraint(
            "confidence IS NULL OR (confidence >= 0 AND confidence <= 1)", name="confidence_range"
        ),
    )

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return (
            f"NarrativeRelation({self.from_narrative_id!r} "
            f"-{self.relation_type}-> {self.to_narrative_id!r})"
        )
